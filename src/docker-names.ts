/**
 * Generate a random Docker-style name: `<adjective>-<noun>`.
 * If `taken` is provided, ensures the returned name is not in the set.
 */
export function generateDockerName(taken?: ReadonlySet<string>): string {
  for (let attempt = 0; attempt < 20; attempt++) {
    const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
    const noun = NOUNS[Math.floor(Math.random() * NOUNS.length)];
    const candidate = `${adj}-${noun}`;
    if (!taken?.has(candidate.toLowerCase())) {
      return candidate;
    }
  }

  // Fallback if random attempts collided
  const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
  const noun = NOUNS[Math.floor(Math.random() * NOUNS.length)];
  const base = `${adj}-${noun}`;
  if (!taken) return base;

  let n = 2;
  while (taken.has(`${base}-${n}`.toLowerCase()) && n < 1000) {
    n++;
  }
  return `${base}-${n}`;
}
